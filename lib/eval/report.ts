import { JUDGE_CRITERIA } from '@/lib/schemas'
import { fmt, fmtPct, fmtUsd } from './stats'
import { getScenario } from './scenarios'
import type { BakeoffComparison, BakeoffResult, ContestantSummary } from './bakeoff'

/**
 * `eval/results/bakeoff-<date>.md` - JUDGE_AGENT.md §6's report, generated rather than
 * written by hand so it cannot quietly omit the section that looks bad.
 *
 * `BAKEOFF_REPORT_SECTIONS` is the contract: §6 lists what the report must cover, and the
 * §7 VT asserts every one of these headings is present in the generated markdown. Adding a
 * section here without generating it fails that test, which is the point.
 */
export const BAKEOFF_REPORT_SECTIONS = [
  'How to read this report',
  'Run configuration',
  'Models and prices',
  'Judge calibration',
  'Quality — contestant × criterion',
  'Pairwise against the baseline',
  'Judge agreement (second judge)',
  'Cost',
  'Latency',
  'Quality per dollar',
  'Best and worst moments',
  'Cost reconciliation with generation_logs',
  'Decision rule',
  'Hybrid option',
  'Caveats and known limitations',
  'Appendix — per-scenario detail',
] as const

/** §6's "$/story at 1,000 and 10,000 stories per month". */
const VOLUMES = [1_000, 10_000] as const

/** Stated assumption for the hybrid blend: one story in ten opens a new series. */
export const HYBRID_FIRST_STORY_SHARE = 0.1

/** §6's decision rule thresholds. Loosening either needs the owner's sign-off. */
export const DECISION_RULE = { max_loss_rate: 0.25, max_gate_flag_rate: 0.05 } as const

function winRate(t: { wins: number; ties: number; losses: number } | null): number {
  if (!t) return Number.NaN
  const n = t.wins + t.ties + t.losses
  return n === 0 ? Number.NaN : t.wins / n
}

function lossRate(t: { wins: number; ties: number; losses: number } | null): number {
  if (!t) return Number.NaN
  const n = t.wins + t.ties + t.losses
  return n === 0 ? Number.NaN : t.losses / n
}

function judgeCaveat(s: ContestantSummary): string {
  return s.is_also_a_judge ? ' ⚠️' : ''
}

function table(header: string[], rows: string[][]): string {
  const sep = header.map(() => '---')
  return [header, sep, ...rows].map((r) => `| ${r.join(' | ')} |`).join('\n')
}

function excerptsFor(result: BakeoffResult, contestant: string): {
  best: { scenario: string; overall: number; quote: string }[]
  worst: { scenario: string; overall: number; quote: string }[]
} {
  const mine = result.stories.filter((s) => s.contestant === contestant && s.overall_final !== null)
  const byBest = [...mine].sort((a, b) => b.overall_final! - a.overall_final!)
  const byWorst = [...mine].sort((a, b) => a.overall_final! - b.overall_final!)
  const pick = (
    pool: typeof mine,
    field: 'best_moment' | 'worst_moment',
  ): { scenario: string; overall: number; quote: string }[] =>
    pool
      .filter((s) => (s[field] ?? '').trim() !== '')
      .slice(0, 3)
      .map((s) => ({ scenario: s.scenario_id, overall: s.overall_final!, quote: s[field]!.trim() }))
  return { best: pick(byBest, 'best_moment'), worst: pick(byWorst, 'worst_moment') }
}

export function renderBakeoffReport(result: BakeoffResult): string {
  const out: string[] = []
  const baselineSummary = result.summaries.find((s) => s.model === result.config.baseline)
  const best = [...result.summaries]
    .filter((s) => Number.isFinite(s.overall_median))
    .sort((a, b) => b.overall_median - a.overall_median)[0]
  const anyJudgeContestant = result.summaries.some((s) => s.is_also_a_judge)

  out.push(`# Model bake-off — ${result.date}`)
  out.push('')
  out.push(
    `Generated by \`pnpm bakeoff\` from \`JUDGE_AGENT.md\` §6. Run at ${result.ran_at}. ` +
      `Judge prompt \`${result.judge_prompt.version}\` (sha ${result.judge_prompt.sha256}). ` +
      `Prices from \`config/pricing.json\` as of ${result.pricing_updated_at}.`,
  )
  out.push('')

  if (result.synthetic) {
    out.push(
      '> **THIS IS NOT A BAKE-OFF RESULT.** The stories in this run came from the fixture ' +
        `pipeline (${result.pipeline_describe}), not from the contestants. Every score, ` +
        'verdict and cost figure below describes the harness. It is here so the report ' +
        'format can be reviewed before any money is spent.',
    )
    out.push('')
  }

  // 1 ----------------------------------------------------------------------
  out.push('## How to read this report')
  out.push('')
  out.push(
    '- **Scores are medians of 3 samples**, not single draws (§2). The `min` column next to each median is the worst sample, and a wide gap between them matters more than a small gap between medians.',
  )
  out.push(
    '- **Pairwise is the number to trust.** Absolute LLM scores cluster near 4/5 and hide differences; every pairwise comparison here ran in both A/B orders and a verdict that flipped is recorded as a TIE.',
  )
  out.push(
    '- **The judge was blind.** It never saw a model id, a price or a cost. That is asserted on every payload, not assumed.',
  )
  out.push(
    `- **The overall is our arithmetic, not the judge's.** Criterion scores come from the judge; the weighted overall and the automatic caps are recomputed in our code (DECISIONS.md #11, #12).`,
  )
  if (anyJudgeContestant) {
    out.push(
      `- **⚠️ marks a contestant that is also a judge.** ${result.config.judge_primary} judged this run and ${result.config.judge_secondary} was the second judge; both are in the field. Self-preference bias is real and is not corrected for here - read those rows against the agreement rate below.`,
    )
  }
  out.push('')

  // 2 ----------------------------------------------------------------------
  out.push('## Run configuration')
  out.push('')
  out.push(
    table(
      ['Setting', 'Value'],
      [
        ['Scenarios', `${result.config.scenarios.length} (${result.config.scenarios.join(', ')})`],
        ['Contestants', result.config.contestants.join(', ')],
        ['Samples per scenario × contestant', String(result.config.samples)],
        ['Pairwise baseline', result.config.baseline],
        ['Primary judge', result.config.judge_primary],
        ['Second judge', result.config.judge_secondary],
        ['Comparisons given a second judge', String(result.config.second_judge_limit)],
        ['Also compared against the best contestant', result.config.pairwise_vs_best ? 'yes' : 'no'],
        ['Pipeline', `${result.pipeline} — ${result.pipeline_describe}`],
        ['Stories scored', String(result.stories.length)],
        ['Pairwise comparisons', String(result.comparisons.length)],
      ],
    ),
  )
  out.push('')

  // 3 ----------------------------------------------------------------------
  out.push('## Models and prices')
  out.push('')
  out.push(
    '§6: "verify current model IDs and prices at docs.claude.com before the run; record them". These are the values this run was priced with.',
  )
  out.push('')
  out.push(
    table(
      ['Model id', 'Name', '$/M input', '$/M output', '$/M cache read'],
      Object.entries(result.models).map(([id, p]) => [
        `\`${id}\``,
        p.display_name,
        p.input.toFixed(2),
        p.output.toFixed(2),
        p.cache_read.toFixed(2),
      ]),
    ),
  )
  out.push('')

  // 4 ----------------------------------------------------------------------
  out.push('## Judge calibration')
  out.push('')
  if ('skipped' in result.calibration) {
    out.push(`**SKIPPED.** ${result.calibration.reason}`)
  } else {
    const cal = result.calibration
    out.push(
      `**${cal.passed ? 'PASS' : 'FAIL'}** — ${cal.judge_calls} judge calls, ${fmtUsd(cal.cost_usd)}. ` +
        `Judge \`${cal.judge_model}\`, prompt \`${cal.judge_prompt.version}@${cal.judge_prompt.sha256}\`.`,
    )
    out.push('')
    out.push(
      table(
        ['Expectation', 'Result', 'Detail'],
        cal.expectations.map((e) => [e.id, e.passed ? 'PASS' : '**FAIL**', e.detail.replace(/\n/g, ' ')]),
      ),
    )
    out.push('')
    out.push(
      table(
        ['Reference story', 'Band', 'Words', 'Overall (raw)', 'Overall (after caps)', 'Caps'],
        cal.reference_scores.map((r) => [
          r.file,
          r.band,
          String(r.word_count),
          r.overall_raw === null ? `judge_error: ${r.judge_error}` : fmt(r.overall_raw),
          r.overall_final === null ? '-' : fmt(r.overall_final),
          r.caps_applied.join(', ') || 'none',
        ]),
      ),
    )
    out.push('')
    for (const note of cal.notes) out.push(`- ${note}`)
  }
  out.push('')

  // 5 ----------------------------------------------------------------------
  out.push('## Quality — contestant × criterion')
  out.push('')
  out.push('Median criterion score across every story the contestant wrote, then the overall.')
  out.push('')
  out.push(
    table(
      [
        'Contestant',
        ...JUDGE_CRITERIA.map((c) => c),
        'Overall (median)',
        'Overall (min)',
        'Disqualified',
        'Gate flag rate',
        'Judge errors',
      ],
      result.summaries.map((s) => [
        `\`${s.model}\`${judgeCaveat(s)}`,
        ...JUDGE_CRITERIA.map((c) => fmt(s.criterion_medians[c] ?? Number.NaN, 1)),
        fmt(s.overall_median),
        fmt(s.overall_min),
        String(s.disqualified),
        fmtPct(s.gate_flag_rate),
        String(s.judge_errors),
      ]),
    ),
  )
  out.push('')
  if (anyJudgeContestant) {
    out.push(
      '⚠️ = this contestant is also one of the judges. Its absolute scores may be inflated by self-preference; prefer its pairwise row and the agreement rate.',
    )
    out.push('')
  }

  // 6 ----------------------------------------------------------------------
  out.push('## Pairwise against the baseline')
  out.push('')
  out.push(
    `Every contestant against \`${result.config.baseline}\` on each scenario, using each one's median-scored story, in both A/B orders. A verdict that flipped between orders is a TIE.`,
  )
  out.push('')
  out.push(
    table(
      ['Contestant', 'Wins', 'Ties', 'Losses', 'Win rate', 'Loss rate', 'Avg confidence'],
      result.summaries.map((s) => [
        `\`${s.model}\`${judgeCaveat(s)}`,
        s.vs_baseline ? String(s.vs_baseline.wins) : '— (is the baseline)',
        s.vs_baseline ? String(s.vs_baseline.ties) : '—',
        s.vs_baseline ? String(s.vs_baseline.losses) : '—',
        fmtPct(winRate(s.vs_baseline)),
        fmtPct(lossRate(s.vs_baseline)),
        s.vs_baseline ? fmt(s.vs_baseline.avg_confidence) : '—',
      ]),
    ),
  )
  out.push('')
  if (best && best.model !== result.config.baseline && result.summaries.some((s) => s.vs_best)) {
    out.push(`Against the top-scoring contestant \`${best.model}\`, which the §6 decision rule is written in terms of:`)
    out.push('')
    out.push(
      table(
        ['Contestant', 'Wins', 'Ties', 'Losses', 'Loss rate', 'Avg confidence'],
        result.summaries
          .filter((s) => s.vs_best)
          .map((s) => [
            `\`${s.model}\`${judgeCaveat(s)}`,
            String(s.vs_best!.wins),
            String(s.vs_best!.ties),
            String(s.vs_best!.losses),
            fmtPct(lossRate(s.vs_best)),
            fmt(s.vs_best!.avg_confidence),
          ]),
      ),
    )
    out.push('')
  }
  const flipped = result.comparisons.filter((c) => c.flipped).length
  out.push(
    `Position flips: ${flipped} of ${result.comparisons.length} comparisons disagreed between orders and were recorded as ties. A high flip rate means the judge is not discriminating on these pairs, not that the models are equal.`,
  )
  out.push('')

  // 7 ----------------------------------------------------------------------
  out.push('## Judge agreement (second judge)')
  out.push('')
  out.push(
    `§6 step 5: the ${result.agreement.comparisons_double_judged} closest comparisons were re-scored by \`${result.agreement.second_judge_model}\`. This is the only check we have on the primary judge, and it matters more than usual because the primary judge is also a contestant.`,
  )
  out.push('')
  out.push(
    table(
      ['Measure', 'Value'],
      [
        ['Comparisons double-judged', String(result.agreement.comparisons_double_judged)],
        ['Agreement on the winner', fmtPct(result.agreement.winner_agreement_rate)],
        ['Per-criterion directional agreement', fmtPct(result.agreement.criterion_agreement_rate)],
      ],
    ),
  )
  out.push('')
  const doubled = result.comparisons.filter((c) => c.second_judge)
  if (doubled.length > 0) {
    out.push(
      table(
        ['Scenario', 'Challenger', 'Baseline', 'Primary verdict', 'Second judge', 'Agrees'],
        doubled.map((c) => [
          c.scenario_id,
          `\`${c.challenger}\``,
          `\`${c.baseline}\``,
          `${c.verdict}${c.flipped ? ' (flip)' : ''} @ ${fmt(c.confidence)}`,
          `${fmt(c.second_judge!.challenger_overall ?? Number.NaN)} vs ${fmt(c.second_judge!.baseline_overall ?? Number.NaN)}`,
          c.second_judge!.agrees_on_winner ? 'yes' : '**no**',
        ]),
      ),
    )
    out.push('')
  }

  // 8 ----------------------------------------------------------------------
  out.push('## Cost')
  out.push('')
  out.push('Per-story cost is the whole pipeline for that story, not just the writing call.')
  out.push('')
  out.push(
    table(
      ['Contestant', 'Median $/story', 'p95 $/story', ...VOLUMES.map((v) => `$/month at ${v.toLocaleString('en-US')}`)],
      result.summaries.map((s) => [
        `\`${s.model}\``,
        fmtUsd(s.median_cost_usd),
        fmtUsd(s.p95_cost_usd),
        ...VOLUMES.map((v) =>
          Number.isFinite(s.median_cost_usd) ? `$${(s.median_cost_usd * v).toFixed(2)}` : '-',
        ),
      ]),
    ),
  )
  out.push('')
  out.push(
    `This run itself cost ${fmtUsd(result.cost.total_usd)}: ${fmtUsd(result.cost.generation_usd)} generating stories and ${fmtUsd(result.cost.judge_usd)} judging them (calibration included).`,
  )
  out.push('')

  // 9 ----------------------------------------------------------------------
  out.push('## Latency')
  out.push('')
  out.push(
    table(
      ['Contestant', 'p50 to first chapter', 'p95 to first chapter', 'p50 to completion', 'p95 to completion'],
      result.summaries.map((s) => [
        `\`${s.model}\``,
        s.median_first_chapter_ms === null ? 'not measured' : `${fmt(s.median_first_chapter_ms / 1000, 1)}s`,
        s.p95_first_chapter_ms === null ? 'not measured' : `${fmt(s.p95_first_chapter_ms / 1000, 1)}s`,
        `${fmt(s.median_total_latency_ms / 1000, 1)}s`,
        `${fmt(s.p95_total_latency_ms / 1000, 1)}s`,
      ]),
    ),
  )
  out.push('')

  // 10 ---------------------------------------------------------------------
  out.push('## Quality per dollar')
  out.push('')
  const baselineCost = baselineSummary?.median_cost_usd ?? Number.NaN
  out.push(
    table(
      ['Contestant', 'Overall median ÷ median $', 'Cost ratio vs baseline', 'Win rate ÷ cost ratio'],
      result.summaries.map((s) => {
        const ratio = s.median_cost_usd / baselineCost
        const wr = winRate(s.vs_baseline)
        return [
          `\`${s.model}\`${judgeCaveat(s)}`,
          Number.isFinite(s.median_cost_usd) && s.median_cost_usd > 0
            ? fmt(s.overall_median / s.median_cost_usd, 1)
            : '-',
          Number.isFinite(ratio) ? `${fmt(ratio)}×` : '-',
          Number.isFinite(wr) && Number.isFinite(ratio) && ratio > 0 ? fmt(wr / ratio) : '—',
        ]
      }),
    ),
  )
  out.push('')
  out.push(
    'Quality per dollar is a ratio of a bounded score to an unbounded cost, so it always favours the cheapest contestant. Use it to rank, never to decide - the decision rule below is what decides.',
  )
  out.push('')

  // 11 ---------------------------------------------------------------------
  out.push('## Best and worst moments')
  out.push('')
  out.push('Up to three verbatim excerpts per contestant, chosen by the judge: best moments from its highest-scoring stories, worst moments from its lowest.')
  out.push('')
  for (const s of result.summaries) {
    const { best: bestQuotes, worst: worstQuotes } = excerptsFor(result, s.model)
    out.push(`### \`${s.model}\`${judgeCaveat(s)}`)
    out.push('')
    if (bestQuotes.length === 0 && worstQuotes.length === 0) {
      out.push('_The judge returned no excerpts for this contestant._')
      out.push('')
      continue
    }
    for (const q of bestQuotes) {
      out.push(`- **best** (${q.scenario}, overall ${fmt(q.overall)}): "${q.quote}"`)
    }
    for (const q of worstQuotes) {
      out.push(`- **worst** (${q.scenario}, overall ${fmt(q.overall)}): "${q.quote}"`)
    }
    out.push('')
  }

  // 12 ---------------------------------------------------------------------
  out.push('## Cost reconciliation with generation_logs')
  out.push('')
  const rec = result.cost.reconciliation
  out.push(
    table(
      ['Measure', 'Value'],
      [
        ['Generation cost reported above', fmtUsd(rec.reported_generation_usd)],
        ['Generation cost summed from generation_logs', fmtUsd(rec.logged_generation_usd)],
        ['Difference', `${fmt(rec.delta_pct, 4)}%`],
        ['Within the 0.1% tolerance', rec.within_tolerance ? 'yes' : '**no**'],
        ['Log rows written by this run', String(rec.log_rows)],
      ],
    ),
  )
  out.push('')
  out.push(
    'Judge calls are excluded from the generation figure: they are the cost of measuring, not the cost of a story.',
  )
  out.push('')

  // 13 ---------------------------------------------------------------------
  out.push('## Decision rule')
  out.push('')
  out.push(
    `§6 default: **pick the cheapest contestant whose pairwise loss rate against the best contestant is ≤ ${fmtPct(DECISION_RULE.max_loss_rate, 0)} and whose gate flag rate is ≤ ${fmtPct(DECISION_RULE.max_gate_flag_rate, 0)}.** The owner makes the final call (F14 AC); this is the rule applied mechanically to the numbers above.`,
  )
  out.push('')
  const eligible = result.summaries
    .map((s) => {
      const against = s.model === best?.model ? null : (s.vs_best ?? s.vs_baseline)
      const loss = s.model === best?.model ? 0 : lossRate(against)
      const lossOk = Number.isFinite(loss) && loss <= DECISION_RULE.max_loss_rate
      const flagOk =
        Number.isFinite(s.gate_flag_rate) && s.gate_flag_rate <= DECISION_RULE.max_gate_flag_rate
      const measured = s.model === best?.model || against !== null
      return { s, loss, lossOk, flagOk, measured, eligible: lossOk && flagOk && measured }
    })
    .sort((a, b) => a.s.median_cost_usd - b.s.median_cost_usd)
  out.push(
    table(
      ['Contestant', 'Median $/story', 'Loss rate vs best', 'Gate flag rate', 'Meets the rule'],
      eligible.map((e) => [
        `\`${e.s.model}\`${judgeCaveat(e.s)}`,
        fmtUsd(e.s.median_cost_usd),
        e.measured ? fmtPct(e.loss) : 'not measured',
        fmtPct(e.s.gate_flag_rate),
        e.eligible ? 'yes' : 'no',
      ]),
    ),
  )
  out.push('')
  const pick = eligible.find((e) => e.eligible)
  out.push(
    pick
      ? `**Rule picks \`${pick.s.model}\`** at ${fmtUsd(pick.s.median_cost_usd)} per story (loss rate ${fmtPct(pick.loss)} against \`${best?.model ?? 'n/a'}\`, gate flag rate ${fmtPct(pick.s.gate_flag_rate)}).`
      : '**No contestant meets the rule.** Either the quality bar or the flag-rate bar needs the owner\'s attention before a model is chosen.',
  )
  out.push('')
  out.push(
    `Recorded for the README (F14 AC): chosen model — _owner to confirm_; report date — ${result.date}.`,
  )
  out.push('')

  // 14 ---------------------------------------------------------------------
  out.push('## Hybrid option')
  out.push('')
  const topTier = best
  const cheap = baselineSummary
  if (topTier && cheap && topTier.model !== cheap.model) {
    const blended =
      topTier.median_cost_usd * HYBRID_FIRST_STORY_SHARE +
      cheap.median_cost_usd * (1 - HYBRID_FIRST_STORY_SHARE)
    const clear =
      Number.isFinite(topTier.overall_median) &&
      Number.isFinite(cheap.overall_median) &&
      topTier.overall_median > cheap.overall_median &&
      (topTier.vs_baseline ? topTier.vs_baseline.wins > topTier.vs_baseline.losses : true)
    out.push(
      `§6: "if Opus wins clearly, also report a hybrid option: the top-tier model for the first story of a new series (where the recurring characters are invented, which sets the tone for everything after) and the cheaper model for subsequent stories."`,
    )
    out.push('')
    out.push(
      `Top tier here is \`${topTier.model}\` (overall median ${fmt(topTier.overall_median)}), cheaper tier \`${cheap.model}\` (${fmt(cheap.overall_median)}). Does the top tier win clearly? **${clear ? 'yes' : 'no'}**.`,
    )
    out.push('')
    out.push(
      table(
        ['Assumption', 'Value'],
        [
          ['Share of stories that open a new series', fmtPct(HYBRID_FIRST_STORY_SHARE, 0)],
          [`First story on \`${topTier.model}\``, fmtUsd(topTier.median_cost_usd)],
          [`Later stories on \`${cheap.model}\``, fmtUsd(cheap.median_cost_usd)],
          ['**Blended $/story**', `**${fmtUsd(blended)}**`],
          ...VOLUMES.map((v) => [`Blended $/month at ${v.toLocaleString('en-US')}`, `$${(blended * v).toFixed(2)}`] as string[]),
        ],
      ),
    )
    out.push('')
    out.push(
      `The share of series-opening stories is an assumption, not a measurement: it is the one number here that will move once real families use the product. Re-derive it from \`stories\` grouped by \`series_id\` after launch.`,
    )
  } else {
    out.push(
      'Not applicable: the top-scoring contestant and the baseline are the same model, so there are no two tiers to blend.',
    )
  }
  out.push('')

  // 15 ---------------------------------------------------------------------
  out.push('## Caveats and known limitations')
  out.push('')
  for (const note of result.notes) out.push(`- ${note}`)
  out.push(
    `- Haiku 4.5 uses the older tokenizer, so its token counts are not comparable with the 4.7+ models for identical text. Cost here is measured from \`generation_logs\`, not estimated from word counts, which is why that does not distort the comparison.`,
  )
  out.push(
    `- Absolute scores are a judge's opinion expressed as an integer. They are useful for spotting a collapse on one criterion, not for fine distinctions.`,
  )
  out.push('')

  // 16 ---------------------------------------------------------------------
  out.push('## Appendix — per-scenario detail')
  out.push('')
  for (const id of result.config.scenarios) {
    let why = ''
    try {
      why = getScenario(id).why
    } catch {
      why = '(scenario no longer in lib/eval/scenarios.ts)'
    }
    out.push(`### ${id}`)
    out.push('')
    out.push(`_${why}_`)
    out.push('')
    const rows = result.stories.filter((s) => s.scenario_id === id)
    out.push(
      table(
        ['Contestant', 'Sample', 'Words', 'Target', 'Overall', 'Caps', 'Gate', '$'],
        rows.map((s) => [
          `\`${s.contestant}\``,
          String(s.sample),
          String(s.word_count),
          `${s.target_words.min}-${s.target_words.max}`,
          s.overall_final === null ? `judge_error` : fmt(s.overall_final),
          s.caps_applied.join(', ') || 'none',
          s.gate ? s.gate.outcome : 'not run',
          fmtUsd(s.generation_cost_usd),
        ]),
      ),
    )
    out.push('')
    const comps = result.comparisons.filter((c) => c.scenario_id === id)
    if (comps.length > 0) {
      out.push(
        table(
          ['Challenger', 'vs', 'First order', 'Swapped', 'Resolved', 'Confidence'],
          comps.map((c: BakeoffComparison) => [
            `\`${c.challenger}\``,
            `\`${c.baseline}\``,
            c.first_order_verdict ?? 'error',
            c.swapped_order_verdict ?? 'error',
            `${c.verdict}${c.flipped ? ' (flip)' : ''}`,
            fmt(c.confidence),
          ]),
        ),
      )
      out.push('')
    }
  }

  return `${out.join('\n')}\n`
}
